#!/bin/bash
# Rebuilds supabase/frankfurt-schema.sql from the numbered migrations.
cd "$(dirname "$0")/../.." || exit 1
{
  echo "-- Full schema for a fresh Supabase project (all migrations, in order)."
  echo "-- Generated by scripts/frankfurt-migration/build-schema.sh — do not edit by hand."
  echo "-- Paste into the SQL editor of the NEW project and run once (choose \"Run without RLS\" if asked)."
  echo
  for f in supabase/migrations/*.sql; do
    echo "-- ===== $(basename "$f") ====="
    cat "$f"
    echo
  done
} > supabase/frankfurt-schema.sql
echo "wrote supabase/frankfurt-schema.sql"
